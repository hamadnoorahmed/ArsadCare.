#Generating simulated data for the Kingdom's cities and preparing the PHRI equation.

import numpy as np
import pandas as pd

np.random.seed(42)
num_samples = 3000

# 1. Generating weather elements for the climates of the Kingdom's cities (Riyadh, Eastern Province, Makkah, Madinah)
temperature_c = np.random.uniform(15.0, 50.0, num_samples)      # temperature
humidity_pct = np.random.uniform(5.0, 85.0, num_samples)        # Humidity
pm10_ug_m3 = np.random.uniform(20.0, 500.0, num_samples)        # PM10 (dust) level
wind_speed_kmh = np.random.uniform(5.0, 65.0, num_samples)      # Wind speed

# 2. Application of the Composite Hazard Risk Index (PHRI) formula
raw_phri = (
    0.40 * (temperature_c / 50.0) +
    0.35 * (pm10_ug_m3 / 500.0) +
    0.15 * (humidity_pct / 100.0) +
    0.10 * (wind_speed_kmh / 70.0)
) * 100

phri_score = np.clip(raw_phri + np.random.normal(0, 2, num_samples), 0, 100)

# Calculating the projected percentage increase in emergency cases based on the indicator
projected_er_surge_pct = np.clip((phri_score * 0.35) + np.random.normal(0, 1.5, num_samples), 0, 50)

df = pd.DataFrame({
    'temperature_c': temperature_c,
    'humidity_pct': humidity_pct,
    'pm10_ug_m3': pm10_ug_m3,
    'wind_speed_kmh': wind_speed_kmh,
    'phri_score': phri_score,
    'projected_er_surge_pct': projected_er_surge_pct
})

df.to_csv("weather_phri_dataset.csv", index=False)

print("The data is ready.")
